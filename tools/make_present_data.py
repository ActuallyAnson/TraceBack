#!/usr/bin/env python3
"""Extract what the video presentation (docs/present.html) shows from the committed incident exports (docs/data/*.json), so no figure on screen is typed by hand.
usage: make_present_data.py   (writes docs/present-data.js)"""
import json, pathlib
D = pathlib.Path(__file__).resolve().parent.parent / "docs"
out = {}
for i in ("inc-026", "inc-003"):
    d = json.loads((D / "data" / f"{i}.json").read_text())
    tb = d["traceback"]["answer"]; bl = d["baseline"]["answer"]
    cites = [c for s in tb["causal_chain"] for c in s["cites"]]
    out[i] = dict(
        truth=d["truth"], symptom=d["symptom"], counts=d["counts"],
        series={s: [dict(t=m["t"], req=m["req"], err=m["err"]) for m in v] for s, v in d["series"].items()},
        baseline=dict(raw=d["baseline"]["raw"], root=bl["root_cause"], confidence=bl["confidence"], correct=d["baseline"]["correct"], cost=d["baseline"]["cost"]),
        traceback=dict(root=tb["root_cause"], confidence=tb["confidence"], llm_confidence=d["traceback"]["llm_confidence"], correct=d["traceback"]["correct"], cost=d["traceback"]["cost"],
                       chain=tb["causal_chain"], verification=d["traceback"]["verification"]),
        hypotheses=[dict(rank=h["rank"], category=h["category"], service=h["service"], score=h["score"]) for h in d["hypotheses"][:4]],
        replays={k: dict(status=v["status"], observed=v.get("rate_observed"), disabled=v.get("rate_disabled")) for k, v in d["replays"].items()},
        records={c: d["records"][c] for c in cites if c in d["records"]},
        analyzer=d["analyzer"])
(D / "present-data.js").write_text("// generated by tools/make_present_data.py from docs/data/*.json; do not edit\nconst PD = " + json.dumps(out, separators=(",", ":")) + ";\n")
print("ok", (D / "present-data.js").stat().st_size, "bytes")
