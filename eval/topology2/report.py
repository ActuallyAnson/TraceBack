#!/usr/bin/env python3
"""Generate the topology-2 generalization tables (summary + every incident) and refresh the README block.

    python3 eval/topology2/report.py            write eval/topology2/RESULTS.md and refresh README.md
    python3 eval/topology2/report.py --check    fail if README.md's block differs from the generated one

Runs the unchanged analyzer, and reads model answers from eval/llm_cache (no API key needed; a cache miss would call the
model). Reproduction runs are not logged in eval/topology2/runs.log; only the original scoring runs are.
"""
import json, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT / "eval"))
import score  # noqa: E402

score.DATA = ROOT / "runs/topo2"
score.SPLIT_FILE = ROOT / "eval/topology2/manifest.json"
ids = score.load_split("test")
pc = lambda x: f"{x*100:.1f}%"
usd = lambda x: "$0" if not x else (f"${x:.4f}" if x < 0.01 else f"${x:.3f}")

rows = []
for iid in ids:
    label = json.loads((score.DATA / "labels" / f"{iid}.json").read_text())
    an, _ = score.run_analyzer(iid)
    tb = score.run_llm(iid, "traceback")
    bl = score.run_llm(iid, "baseline")
    vs = score.run_verify(iid, tb)
    r = {"id": iid, "label": label, "group": label["group"], "type": label["root_cause"]["type"]}
    r["an"] = (*score.judge(label, an)[:1], an["hypotheses"][0], an["confidence"])
    tbr, blr = score.llm_as_report(tb), score.llm_as_report(bl)
    r["tb"] = (score.judge(label, tbr)[0], tbr["hypotheses"][0], tbr["confidence"], vs, score.final_conf(tbr["confidence"], vs))
    r["bl"] = (score.judge(label, blr)[0], blr["hypotheses"][0], blr["confidence"])
    r["cost_tb"], r["cost_bl"] = tb["meta"]["cost_usd"], bl["meta"]["cost_usd"]
    r["lat_tb"], r["lat_bl"] = tb["meta"]["latency_s"], bl["meta"]["latency_s"]
    r["trunc"] = bl["meta"].get("baseline", {}).get("truncated")
    rows.append(r)


def agg(ok, conf, cost, lat, rows_):
    n = len(rows_)
    high = [i for i in range(n) if conf[i] == "high"]
    return dict(top1=sum(ok) / n, high=len(high), prec=(sum(ok[i] for i in high) / len(high)) if high else None,
                fc=sum(1 for i in high if not ok[i]) / n, cost=sum(cost) / n, lat=sum(lat) / n)


systems = [
    ("Raw logs → LLM (baseline)", agg([r["bl"][0] for r in rows], [r["bl"][2] for r in rows], [r["cost_bl"] for r in rows], [r["lat_bl"] for r in rows], rows)),
    ("Analyzer only (no LLM)", agg([r["an"][0] for r in rows], [r["an"][2] for r in rows], [0] * len(rows), [0.05] * len(rows), rows)),
    ("Analyzer + LLM (no verifier)", agg([r["tb"][0] for r in rows], [r["tb"][2] for r in rows], [r["cost_tb"] for r in rows], [r["lat_tb"] for r in rows], rows)),
    ("**Full Traceback** (analyzer + LLM + verifier)", agg([r["tb"][0] for r in rows], [r["tb"][4] for r in rows], [r["cost_tb"] for r in rows], [r["lat_tb"] for r in rows], rows)),
]
L = ["<!-- TOPOLOGY2:START (generated by eval/topology2/report.py; do not edit by hand) -->", "",
     f"**Second topology (event-driven fan-out, 6 services), n={len(rows)}, analyzer and prompts unchanged**", "",
     "| System | Top-1 | Precision when “high” | Confidently wrong | Cost / incident | Latency |", "|---|---:|---:|---:|---:|---:|"]
for name, v in systems:
    L.append(f"| {name} | {pc(v['top1'])} | {'–' if v['prec'] is None else pc(v['prec']) + ' (' + str(v['high']) + ')'} | {pc(v['fc'])} | {usd(v['cost'])} | {'<0.1 s' if v['lat'] < 1 else format(v['lat'], '.1f') + ' s'} |")
by = {}
for r in rows:
    by.setdefault(r["group"], []).append(r)
L += ["", "Top-1 by group:", "", "| Group (n) | Baseline | Analyzer | Analyzer + LLM |", "|---|---:|---:|---:|"]
for g, rs in sorted(by.items()):
    f = lambda k: pc(sum(r[k][0] for r in rs) / len(rs))
    L.append(f"| {g} ({len(rs)}) | {f('bl')} | {f('an')} | {f('tb')} |")
mark = lambda ok: "✓" if ok else "✗"
L += ["", "Every incident (✓ = top-1 correct; the answer is shown for every ✗). Truth is the labeled cause; “replay” is the verifier's verdict on the LLM's answer:", "",
      "| Incident | Truth (service) | Analyzer | Baseline | Analyzer + LLM (confidence → after replay) |", "|---|---|---|---|---|"]
for r in rows:
    rc = r["label"]["root_cause"]
    edge = f" {rc['edge']['from']}→{rc['edge']['to']}" if rc.get("edge") else ""
    fmt = lambda t: f"{mark(t[0])}" if t[0] else f"✗ {t[1]['category']}/{t[1]['service']}"
    tb = r["tb"]
    L.append(f"| {r['id']} ({r['group']}) | {rc['type']} ({rc['service']}{edge}) | {fmt(r['an'])} | {fmt(r['bl'])} | {fmt(tb)} ({tb[2]} → {tb[4]}; replay {tb[3]}) |")
n_trunc = sum(1 for r in rows if r["trunc"])
L += ["", f"Baseline input exceeded the context window and was sampled by trace for {n_trunc} of {len(rows)} incidents. Unmapped fault types (network partition, crash loop, silent regression) are scored on service localization only, as in the first topology.", "",
      "<!-- TOPOLOGY2:END -->"]
block = "\n".join(L)
# Data for the site's "Second topology" view (docs/data/topology2.json); same rows as the tables above.
def sysrow(name, v):
    return dict(name=name, top1=v["top1"], high=v["high"], prec=v["prec"], fc=v["fc"], cost=v["cost"], lat=v["lat"])
site_rows = []
for r in rows:
    tbr_, vs_ = r["tb"][1], r["tb"][3]
    rc = r["label"]["root_cause"]
    site_rows.append(dict(
        id=r["id"], group=r["group"], truth=dict(type=rc["type"], service=rc["service"], edge=rc.get("edge"), decoys=r["label"]["decoys"]),
        an=dict(ok=r["an"][0], cat=r["an"][1]["category"], svc=r["an"][1]["service"], conf=r["an"][2]),
        bl=dict(ok=r["bl"][0], cat=r["bl"][1]["category"], svc=r["bl"][1]["service"], conf=r["bl"][2], cost=r["cost_bl"], trunc=bool(r["trunc"])),
        tb=dict(ok=r["tb"][0], cat=tbr_["category"], svc=tbr_["service"], llm_conf=r["tb"][2], final_conf=r["tb"][4], replay=vs_ if isinstance(vs_, str) else (vs_.get("status") if isinstance(vs_, dict) else str(vs_)), cost=r["cost_tb"])))
site_json = json.dumps(dict(n=len(rows), systems=[sysrow(n, v) for n, v in systems], incidents=site_rows), separators=(",", ":"), sort_keys=True)
SITE = ROOT / "docs/data/topology2.json"
readme = ROOT / "README.md"
txt = readme.read_text()
a, b = txt.find("<!-- TOPOLOGY2:START"), txt.find("<!-- TOPOLOGY2:END -->")
if "--check" in sys.argv:
    if a < 0 or b < 0 or txt[a:b + len("<!-- TOPOLOGY2:END -->")] != block:
        sys.exit("README.md topology-2 block is missing or out of date; run `make topology2`")
    if not SITE.exists() or SITE.read_text() != site_json:
        sys.exit("docs/data/topology2.json is missing or out of date; run `make topology2`")
    print("README topology-2 block and docs/data/topology2.json match the generated results")
    sys.exit(0)
SITE.write_text(site_json)
(ROOT / "eval/topology2/RESULTS.md").write_text("# Topology-2 results (generated)\n\n" + block + "\n")
if a >= 0 and b >= 0:
    readme.write_text(txt[:a] + block + txt[b + len("<!-- TOPOLOGY2:END -->"):])
print(block)
