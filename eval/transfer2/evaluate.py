#!/usr/bin/env python3
"""Transfer test (eval/transfer2/PLAN.md): raw-logs baseline vs hybrid 2 on RCAEval RE3-SS and RE3-TT, once.

    evaluate.py            run (answers from eval/llm_cache; a miss calls the model and needs NEBIUS_API_KEY), write eval/transfer2/RESULTS.md, refresh the README block
    evaluate.py --check    fail if RESULTS.md or the README block differ from the regenerated ones (offline)
"""
import json, pathlib, subprocess, sys
HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
CACHE = ROOT / "eval/llm_cache"


def run(exe, d, extra=()):
    p = subprocess.run([str(ROOT / "build" / exe), str(d), "--cache", str(CACHE), *extra], capture_output=True, text=True)
    if p.returncode:
        sys.exit(f"{exe} {d}: {p.stderr.strip()[:300]}")
    return json.loads(p.stdout)


def ok(lab, svc):
    return svc == lab["root_cause"]["service"]


def collect():
    rows, cost = [], 0.0
    for lp in sorted((HERE / "test/labels").glob("*.json")):
        lab = json.loads(lp.read_text())
        d = HERE / "test/data/incidents" / lab["id"]
        r = dict(id=lab["id"], lab=lab)
        for k, exe, extra in (("bl", "tb_reason", ["--system", "baseline"]), ("hy", "tb_hybrid2", [])):
            res = run(exe, d, extra)
            a = res.get("answer") or {}
            rc = a.get("root_cause", {"category": "none", "service": "none"})
            r[k] = dict(cat=rc.get("category", ""), svc=rc.get("service", "none"), conf=a.get("confidence", "low"))
            if k == "bl":
                cost += res["meta"]["cost_usd"]
        r["src"] = run("tb_hybrid2", d)["hybrid"]["source"]
        rows.append(r)
    return rows, cost


def summ(rows, k):
    f = [r for r in rows if r["lab"]["kind"] == "fault"]; c = [r for r in rows if r["lab"]["kind"] == "clean"]
    hit = [r for r in f if ok(r["lab"], r[k]["svc"])]
    wrong = [r for r in f if r not in hit]
    return (f"{len(hit)}/{len(f)}", f"{sum(r[k]['conf'] in ('medium', 'high') for r in c)}/{len(c)}", sum(r[k]["conf"] == "high" for r in wrong), sum(r[k]["conf"] in ("medium", "high") for r in wrong),
            sum(r[k]["svc"] == "none" for r in rows))


def build(rows, cost):
    L = ["<!-- TRANSFER2:START (generated by eval/transfer/evaluate.py; do not edit by hand) -->", "",
         "**Larger transfer test (RCAEval RE2-SS Sock Shop, resource and network faults, logs and resource metrics only): all 90 fault cases and 30 clean windows, locked before any system ran (`eval/transfer2/LOCK`); hybrid 2 and its converter are unchanged from the first transfer test.** "
         "Localization is strict (the answer's service equals the dataset's label). A clean-window alarm is a medium or high answer. “No answer” means the system found nothing measurably anomalous. No significance claims.", "",
         "| Data | System | Faults localized | Clean-window alarms | Wrong at high | Wrong at medium or high | No answer |", "|---|---|---:|---:|---:|---:|---:|"]
    for name, sel in (("All", lambda r: True),) + tuple((f"Fault type: {ft}", (lambda r, ft=ft: r["lab"].get("fault_type") == ft or ("-clean-" in r["id"] and r["id"].endswith("-" + ft)))) for ft in ("cpu", "delay", "disk", "loss", "mem", "socket")):
        rs = [r for r in rows if sel(r)]
        for k, sysname in (("bl", "Raw logs → LLM (baseline)"), ("hy", "**Hybrid 2**")):
            a = summ(rs, k)
            L.append(f"| {name} | {sysname} | {a[0]} | {a[1]} | {a[2]} | {a[3]} | {a[4]} |")
    L += ["", "Every case (✓ localized; the answer is shown for every ✗; on clean windows the answer and confidence). “Source” is how hybrid 2 chose.", "", "| Case | Truth | Baseline | Hybrid 2 | Source |", "|---|---|---|---|---|"]
    for r in rows:
        lab = r["lab"]
        truth = "clean" if lab["kind"] == "clean" else lab["root_cause"]["service"]
        def cell(k):
            v = r[k]
            return (("✓" if ok(lab, v["svc"]) else "✗") + f" {v['svc']} ({v['conf']})") if lab["kind"] == "fault" else f"{v['svc']} ({v['conf']})"
        L.append(f"| {r['id']} | {truth} | {cell('bl')} | {cell('hy')} | {r['src']} |")
    wr = lambda k: ", ".join(r["id"] for r in rows if r["lab"]["kind"] == "fault" and not ok(r["lab"], r[k]["svc"])) or "none"
    L += ["", f"Wrong fault-case answers (all of them): baseline: {wr('bl')}; hybrid 2: {wr('hy')}.", "", f"Model cost (the baseline's calls; hybrid 2 reuses them): ${cost:.3f}.", "", "<!-- TRANSFER2:END -->"]
    return "\n".join(L)


def main():
    rows, cost = collect()
    block = build(rows, cost)
    readme = ROOT / "README.md"
    txt = readme.read_text()
    a, b = txt.find("<!-- TRANSFER2:START"), txt.find("<!-- TRANSFER2:END -->")
    end = b + len("<!-- TRANSFER2:END -->")
    head = "# Transfer test (generated)\n\n"
    if "--check" in sys.argv:
        if (HERE / "RESULTS.md").read_text() != head + block + "\n" or a < 0 or txt[a:end] != block:
            sys.exit("transfer results or README block out of date; run `make transfer2`")
        print("transfer results match")
        return
    (HERE / "RESULTS.md").write_text(head + block + "\n")
    if a >= 0:
        readme.write_text(txt[:a] + block + txt[end:])
    print(block)


if __name__ == "__main__":
    main()
