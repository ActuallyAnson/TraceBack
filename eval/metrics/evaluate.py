#!/usr/bin/env python3
"""Rule M results (eval/metrics/PLAN.md) from eval/metrics/scores_<tag>.json (produced by scores.py from the public archives; no model).

    evaluate.py            write eval/metrics/RESULTS.md and refresh the README block
    evaluate.py --check    fail if RESULTS.md or the README block differ from the regenerated ones (offline)
"""
import collections, json, pathlib, sys
HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SETS = [("ss", "RE2 Sock Shop", "development"), ("ob", "RE2 Online Boutique", "test"), ("tt", "RE2 Train Ticket", "test")]


def stats(rows):
    f = [r for r in rows if r["kind"] == "fault"]; c = [r for r in rows if r["kind"] == "clean"]
    return dict(n=len(f), hit=sum(r["answer"] == r["truth"] for r in f), ans=sum(r["answer"] is not None for r in f), cn=len(c), alarm=sum(r["answer"] is not None for r in c),
                top1=sum(r["top_service"] == r["truth"] for r in f))


def build():
    L = ["<!-- METRICS:START (generated by eval/metrics/evaluate.py; do not edit by hand) -->", "",
         "**Rule M (per-service metric anomaly, no model, cost $0) on RCAEval RE2 resource and network faults.** Frozen before the test archives were opened (`eval/metrics/METRICS_HASHES`); Sock Shop was the development data, Online Boutique and Train Ticket the test. "
         "“Localized” = the answer is the case's labelled service; “top-1 without threshold” ranks all services and ignores TAU; a clean-window alarm is an answer on a clean window. No significance claims.", "",
         "| Data | Role | Faults localized | Answered | Top-1 without threshold | Clean-window alarms |", "|---|---|---:|---:|---:|---:|"]
    allrows = {}
    for tag, name, role in SETS:
        p = HERE / f"scores_{tag}.json"
        if not p.exists():
            continue
        rows = json.loads(p.read_text()); allrows[tag] = rows
        s = stats(rows)
        L.append(f"| {name} | {role} | {s['hit']}/{s['n']} | {s['ans']}/{s['n']} | {s['top1']}/{s['n']} | {s['alarm']}/{s['cn']} |")
    L += ["", "By fault type (localized / cases):", "", "| Data | " + " | ".join(["cpu", "delay", "disk", "loss", "mem", "socket"]) + " |", "|---|" + "---:|" * 6]
    for tag, name, role in SETS:
        if tag not in allrows:
            continue
        cells = []
        for ft in ("cpu", "delay", "disk", "loss", "mem", "socket"):
            f = [r for r in allrows[tag] if r["kind"] == "fault" and r["fault_type"] == ft]
            cells.append(f"{sum(r['answer'] == r['truth'] for r in f)}/{len(f)}")
        L.append(f"| {name} | " + " | ".join(cells) + " |")
    L += ["", "Every wrong or missing answer on the test data (case: truth, answer or none, score):", ""]
    for tag, name, role in SETS:
        if role != "test" or tag not in allrows:
            continue
        bad = [f"{r['id']}: {r['truth']}, {r['answer'] or 'none'} ({r['top_service']} {r['top_score']})" for r in allrows[tag] if r["kind"] == "fault" and r["answer"] != r["truth"]]
        L.append(f"- {name} ({len(bad)}): " + "; ".join(bad))
    L += ["", "<!-- METRICS:END -->"]
    return "\n".join(L)


def main():
    block = build()
    readme = ROOT / "README.md"
    txt = readme.read_text()
    a, b = txt.find("<!-- METRICS:START"), txt.find("<!-- METRICS:END -->")
    end = b + len("<!-- METRICS:END -->")
    head = "# Rule M results (generated)\n\n"
    if "--check" in sys.argv:
        if (HERE / "RESULTS.md").read_text() != head + block + "\n" or a < 0 or txt[a:end] != block:
            sys.exit("metrics results or README block out of date; run `make metrics`")
        print("metrics results match")
        return
    (HERE / "RESULTS.md").write_text(head + block + "\n")
    if a >= 0:
        readme.write_text(txt[:a] + block + txt[end:])
    print(block)


if __name__ == "__main__":
    main()
