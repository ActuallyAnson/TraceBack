#!/usr/bin/env python3
"""Third real-telemetry batch (eval/real3/PLAN.md): raw-logs baseline, Full Traceback v2 and the hybrid, once (analyzer v2 for reference).

    evaluate.py            run (answers from eval/llm_cache; a miss calls the model and needs NEBIUS_API_KEY), write eval/real3/RESULTS.md, refresh the README block
    evaluate.py --check    fail if RESULTS.md or the README block differ from the regenerated ones (offline)
"""
import importlib.util, json, pathlib, sys
HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT / "eval")); sys.path.insert(0, str(ROOT / "eval/v2"))
import score, report  # noqa: E402

spec = importlib.util.spec_from_file_location("real1", ROOT / "eval/real/evaluate.py")
real1 = importlib.util.module_from_spec(spec); spec.loader.exec_module(real1)
view, correct = real1.view, real1.correct

SYS = [("bl", "Raw logs → LLM (baseline)"), ("an2", "Analyzer v2 (reference)"), ("tb2", "Full Traceback v2"), ("hy", "**Hybrid** (LLM proposals + deterministic checks)")]
CAPPED = ("tb2", "hy")  # systems with a verifier step; real telemetry has no replay environment, so the verdict is "inconclusive" (high -> medium)


def run3():
    DATA = HERE / "data"
    rows = []
    for lp in sorted((HERE / "labels").glob("*.json")):
        lab = json.loads(lp.read_text())
        iid = lab["id"]
        r = dict(id=iid, lab=lab, cost=0.0)
        rep = report.analyzer("tb_analyze2", DATA, iid)
        r["an2"] = view(rep)
        r["sym"] = report.analyzer("tb_analyze3", DATA, iid)["symptom"]
        for k, system in (("bl", "baseline"), ("tb2", "traceback")):
            args = [ROOT / "build/tb_reason", DATA / "incidents" / iid, "--system", system, "--cache", report.CACHE] + (["--rules", "v2"] if k == "tb2" else [])
            p = report.sh(args)
            if p.returncode:
                sys.exit(f"tb_reason failed on {iid} ({k}): {p.stderr.strip()[:300]}")
            res = json.loads(p.stdout)
            r[k] = view(score.llm_as_report(res))
            r["cost"] += res["meta"]["cost_usd"]
        p = report.sh([ROOT / "build/tb_hybrid", DATA / "incidents" / iid, "--cache", report.CACHE])
        if p.returncode:
            sys.exit(f"tb_hybrid failed on {iid}: {p.stderr.strip()[:300]}")
        res = json.loads(p.stdout)
        r["hy"] = view(score.llm_as_report(res))
        r["hy_info"] = res["hybrid"]
        for k, _ in SYS:
            r[k]["capped"] = score.final_conf(r[k]["conf"], "inconclusive") if k in CAPPED else r[k]["conf"]
            r[k]["ok"] = correct(lab, r[k]) if lab["kind"] == "fault" else None
        rows.append(r)
    return rows


def summ(rows, k):
    f = [r for r in rows if r["lab"]["kind"] == "fault"]
    c = [r for r in rows if r["lab"]["kind"] == "clean"]
    wrong = [r for r in f if not r[k]["ok"]]
    return dict(loc=f"{sum(r[k]['ok'] for r in f)}/{len(f)}", clean=f"{sum(r[k]['conf'] in ('high', 'medium') for r in c)}/{len(c)}",
                clean_cap=f"{sum(r[k]['capped'] in ('high', 'medium') for r in c)}/{len(c)}",
                cw=sum(r[k]["conf"] == "high" for r in wrong), cw_cap=sum(r[k]["capped"] == "high" for r in wrong),
                wmh=sum(r[k]["conf"] in ("high", "medium") for r in wrong))


def build(rows):
    nf, nc = sum(r["lab"]["kind"] == "fault" for r in rows), sum(r["lab"]["kind"] == "clean" for r in rows)
    L = ["<!-- REAL3:START (generated by eval/real3/evaluate.py; do not edit by hand) -->", "",
         f"**Third batch of real telemetry ({nf} fault runs + {nc} clean runs), collected and locked before any system was run on it; the hybrid was frozen before the batch existed.** "
         "Localization only. “As stated” is the system's own confidence; “after the verifier policy” applies what the replay verifier does when it cannot reproduce the effect: real telemetry has no replay environment, so the verdict is inconclusive and a “high” becomes “medium” "
         "(that cap makes “confidently wrong” zero by construction, so wrong answers at medium or high confidence are shown too). A clean-run alarm is a medium or high answer. No significance claims.", "",
         "| System | Faults localized | Clean-run alarms (as stated) | Wrong, high (as stated) | Wrong, medium or high (as stated) | Wrong, high (after verifier policy) | Clean-run alarms (after verifier policy) |", "|---|---:|---:|---:|---:|---:|---:|"]
    for k, name in SYS:
        s = summ(rows, k)
        L.append(f"| {name} | {s['loc']} | {s['clean']} | {s['cw']} | {s['wmh']} | {s['cw_cap']} | {s['clean_cap']} |")
    L += ["", "Every run (✓ = localized; the answer is shown for every ✗; on clean runs the top answer). Confidence as stated → after the verifier policy for the two systems that have a verifier step. “Entry failures” = failed entry requests / entry requests:", "",
          "| Run | Truth | Entry failures | Baseline | Analyzer v2 | Full Traceback v2 | Hybrid |", "|---|---|---:|---|---|---|---|"]
    for r in rows:
        lab = r["lab"]
        truth = "none (clean)" if lab["kind"] == "clean" else f"`{lab['flag']}={lab['variant']}` → {lab['root_cause']['service']}" + (f" ({lab['root_cause']['edge']['from']}→{lab['root_cause']['edge']['to']})" if lab["root_cause"]["edge"] else "")
        def cell(k):
            v = r[k]
            conf = f"{v['conf']} → {v['capped']}" if k in CAPPED and v["conf"] != v["capped"] else v["conf"]
            return (f"{'✓' if v['ok'] else '✗'} {v['cat']}/{v['svc']} ({conf})" if lab["kind"] == "fault" else f"{v['cat']}/{v['svc']} ({conf})")
        L.append(f"| {r['id']} | {truth} | {r['sym']['failed_traces']}/{r['sym']['traces']} | {cell('bl')} | {cell('an2')} | {cell('tb2')} | {cell('hy')} |")
    wrong = {name: [r["id"] for r in rows if r["lab"]["kind"] == "fault" and not r[k]["ok"]] for k, name in SYS}
    L += ["", "Wrong fault-run answers per system (all of them): " + "; ".join(f"{n.replace('**', '')}: {', '.join(v) if v else 'none'}" for n, v in wrong.items()) + ".", ""]
    ch = [r["id"] for r in rows if r["hy_info"].get("chosen", {}).get("challenged_analyzer")]
    dis = [r["id"] for r in rows if r["hy_info"].get("chosen", {}).get("model_disagrees")]
    n_llm = sum(r["hy_info"]["llm_candidates"] for r in rows)
    n_rej = sum(len(r["hy_info"]["rejected"]) for r in rows)
    L += [f"Hybrid internals: the model's proposals that passed validation: {n_llm}; rejected (unknown service, no citation or an id that does not exist): {n_rej}. "
          f"Runs where a model proposal replaced the analyzer's top candidate: {', '.join(ch) if ch else 'none'}. Runs where the model's top proposal named a different service than the one chosen (confidence capped at medium): {', '.join(dis) if dis else 'none'}.", "",
          f"Model cost of this batch (baseline, Full Traceback v2; the hybrid's proposals are the baseline's answer, so it adds no calls): ${sum(r['cost'] for r in rows):.3f}.", "", "<!-- REAL3:END -->"]
    return "\n".join(L)


def main():
    block = build(run3())
    readme = ROOT / "README.md"
    txt = readme.read_text()
    a, b = txt.find("<!-- REAL3:START"), txt.find("<!-- REAL3:END -->")
    end = b + len("<!-- REAL3:END -->")
    head = "# Real-telemetry third batch (generated)\n\n"
    if "--check" in sys.argv:
        if (HERE / "RESULTS.md").read_text() != head + block + "\n" or a < 0 or txt[a:end] != block:
            sys.exit("real3 results or README block out of date; run `make real3`")
        print("real3 results match")
        return
    (HERE / "RESULTS.md").write_text(head + block + "\n")
    if a >= 0:
        readme.write_text(txt[:a] + block + txt[end:])
    print(block)


if __name__ == "__main__":
    main()
