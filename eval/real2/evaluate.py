#!/usr/bin/env python3
"""Second real-telemetry batch (eval/real2/PLAN.md): baseline, analyzers v1/v2/v3, Full Traceback v2/v3, once, plus the first batch as "before".

    evaluate.py            run (answers from eval/llm_cache; a miss calls the model and needs NEBIUS_API_KEY), write eval/real2/RESULTS.md, refresh the README block
    evaluate.py --check    fail if RESULTS.md or the README block differ from the regenerated ones (offline)
"""
import importlib.util, json, pathlib, sys
HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT / "eval")); sys.path.insert(0, str(ROOT / "eval/v2"))
import score, report  # noqa: E402

spec = importlib.util.spec_from_file_location("real1", ROOT / "eval/real/evaluate.py")
real1 = importlib.util.module_from_spec(spec); spec.loader.exec_module(real1)
view, correct = real1.view, real1.correct

SYS = [("bl", "Raw logs → LLM (baseline)"), ("an1", "Analyzer v1"), ("an2", "Analyzer v2"), ("an3", "Analyzer v3 (new)"), ("tb2", "Full Traceback v2"), ("tb3", "Full Traceback v3 (new)")]


def run2():
    DATA = HERE / "data"
    rows = []
    for lp in sorted((HERE / "labels").glob("*.json")):
        lab = json.loads(lp.read_text())
        iid = lab["id"]
        r = dict(id=iid, lab=lab, cost=0.0)
        for k, exe in (("an1", "tb_analyze"), ("an2", "tb_analyze2"), ("an3", "tb_analyze3")):
            rep = report.analyzer(exe, DATA, iid)
            r[k] = view(rep)
            if k == "an3":
                r["sym"] = rep["symptom"]
        for k, system, rules in (("bl", "baseline", "v1"), ("tb2", "traceback", "v2"), ("tb3", "traceback", "v3")):
            args = [ROOT / "build/tb_reason", DATA / "incidents" / iid, "--system", system, "--cache", report.CACHE] + (["--rules", rules] if rules != "v1" else [])
            p = report.sh(args)
            if p.returncode:
                sys.exit(f"tb_reason failed on {iid} ({k}): {p.stderr.strip()[:300]}")
            res = json.loads(p.stdout)
            r[k] = view(score.llm_as_report(res))
            r["cost"] += res["meta"]["cost_usd"]
        for k, _ in SYS:
            r[k]["ok"] = correct(lab, r[k]) if lab["kind"] == "fault" else None
            r[k]["alarm"] = r[k]["conf"] in ("high", "medium") if lab["kind"] == "clean" else None
        rows.append(r)
    return rows


def summ(rows, k):
    f = [r for r in rows if r["lab"]["kind"] == "fault"]
    c = [r for r in rows if r["lab"]["kind"] == "clean"]
    return f"{sum(r[k]['ok'] for r in f)}/{len(f)}", f"{sum(r[k]['alarm'] for r in c)}/{len(c)}", sum(1 for r in f if not r[k]["ok"] and r[k]["conf"] == "high")


def main():
    after = run2()
    before = real1.run("v1")  # first batch, converter v1, from the committed cache: not re-scored, same numbers as eval/real/RESULTS.md
    L = ["<!-- REAL2:START (generated by eval/real2/evaluate.py; do not edit by hand) -->", "",
         f"**Second batch of real telemetry ({sum(r['lab']['kind'] == 'fault' for r in after)} fault runs + {sum(r['lab']['kind'] == 'clean' for r in after)} clean runs), run after the general fixes (analyzer v3) were written and frozen.** "
         "Side by side with the first batch (the frozen “before”, converter v1). Localization only; a clean-run alarm is medium or high confidence; “confidently wrong” = a wrong fault-run answer with high confidence. No significance claims.", "",
         "| System | Batch 1: faults localized | Batch 1: clean alarms | Batch 2: faults localized | Batch 2: clean alarms | Batch 2: confidently wrong |", "|---|---:|---:|---:|---:|---:|"]
    for k, name in SYS:
        b = summ(before, k) if k in before[0] else ("not run", "not run", "–")
        a = summ(after, k)
        L.append(f"| {name} | {b[0]} | {b[1]} | {a[0]} | {a[1]} | {a[2]} |")
    L += ["", "Every incident of the second batch (✓ = localized; the answer is shown for every ✗; on clean runs the top answer and confidence). “Entry failures” = failed entry requests / entry requests as counted by analyzer v3:", "",
          "| Run | Truth | Entry failures | Baseline | Analyzer v2 | Analyzer v3 | Full Traceback v2 | Full Traceback v3 |", "|---|---|---:|---|---|---|---|---|"]
    for r in after:
        lab = r["lab"]
        truth = "none (clean)" if lab["kind"] == "clean" else f"`{lab['flag']}={lab['variant']}` → {lab['root_cause']['service']}" + (f" ({lab['root_cause']['edge']['from']}→{lab['root_cause']['edge']['to']})" if lab["root_cause"]["edge"] else "")
        cell = lambda k: (f"{'✓' if r[k]['ok'] else '✗'} {r[k]['cat']}/{r[k]['svc']} ({r[k]['conf']})" if lab["kind"] == "fault" else f"{r[k]['cat']}/{r[k]['svc']} ({r[k]['conf']})")
        L.append(f"| {r['id']} | {truth} | {r['sym']['failed_traces']}/{r['sym']['traces']} | {cell('bl')} | {cell('an2')} | {cell('an3')} | {cell('tb2')} | {cell('tb3')} |")
    wrong = {name: [r["id"] for r in after if r["lab"]["kind"] == "fault" and not r[k]["ok"]] for k, name in SYS}
    L += ["", "Wrong fault-run answers per system (all of them): " + "; ".join(f"{n}: {', '.join(v) if v else 'none'}" for n, v in wrong.items()) + ".",
          "", f"Model cost of the second batch (baseline, Full Traceback v2 and v3): ${sum(r['cost'] for r in after):.3f}.", "", "<!-- REAL2:END -->"]
    block = "\n".join(L)
    readme = ROOT / "README.md"
    txt = readme.read_text()
    a, b = txt.find("<!-- REAL2:START"), txt.find("<!-- REAL2:END -->")
    end = b + len("<!-- REAL2:END -->")
    head = "# Real-telemetry second batch (generated)\n\n"
    if "--check" in sys.argv:
        if (HERE / "RESULTS.md").read_text() != head + block + "\n" or a < 0 or txt[a:end] != block:
            sys.exit("real2 results or README block out of date; run `make real2`")
        print("real2 results match")
        return
    (HERE / "RESULTS.md").write_text(head + block + "\n")
    if a >= 0:
        readme.write_text(txt[:a] + block + txt[end:])
    print(block)


if __name__ == "__main__":
    main()
