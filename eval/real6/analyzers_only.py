#!/usr/bin/env python3
"""The part of the sixth iteration that needs no model call (eval/real6/PLAN.md): analyzer v5 vs v6 on batch 6 and on the labeled simulator sets. Offline.
The model-side systems (raw-logs baseline, Full Traceback v5 and v6) could not be run on batch 6 because the model endpoint stalled (see README)."""
import glob, json, pathlib, subprocess, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT / "eval")); sys.path.insert(0, str(ROOT / "eval/v2"))
import score, report  # noqa: E402
an = lambda exe, d: json.loads(subprocess.run([str(ROOT / "build" / exe), str(d)], capture_output=True, text=True, check=True).stdout)
print("# Sixth iteration, analyzers only (generated by eval/real6/analyzers_only.py)\n")
print("## Batch 6 (strict rule): analyzer v5 | analyzer v6\n")
ok = {"tb_analyze5": 0, "tb_analyze6": 0}; al = dict(ok); nf = nc = 0
for lp in sorted(glob.glob(str(ROOT / "eval/real6/labels/*.json"))):
    lab = json.loads(open(lp).read()); i = lab["id"]; cells = []
    nf += lab["kind"] == "fault"; nc += lab["kind"] == "clean"
    for exe in ok:
        r = an(exe, ROOT / "eval/real6/data/incidents" / i); t = r["hypotheses"][0]
        if lab["kind"] == "fault":
            rc = lab["root_cause"]; names = {rc["service"]} | ({rc["edge"]["from"], rc["edge"]["to"]} if rc.get("edge") else set())
            ok[exe] += t["service"] in names; cells.append(("✓" if t["service"] in names else "✗") + f" {t['category']}/{t['service']} ({r['confidence']})")
        else:
            al[exe] += r["confidence"] in ("medium", "high"); cells.append(f"clean {t['category']}/{t['service']} ({r['confidence']})")
    print(f"- {i} {lab.get('flag', 'clean')} {lab.get('variant', '')}: " + " | ".join(cells))
print(f"\nFaults localized: v5 {ok['tb_analyze5']}/{nf}, v6 {ok['tb_analyze6']}/{nf}. Clean-run alarms (medium or high): v5 {al['tb_analyze5']}/{nc}, v6 {al['tb_analyze6']}/{nc}.\n")
print("## Simulator sets (analyzer alone, top-1)\n")
sets = []
for t, sim, _ in report.TOPOS:
    data = report.prepare(t, sim)
    sets.append((f"v2 fresh {t}", data, sorted(p.name for p in (data / "incidents").iterdir()), lambda i, t=t: json.loads((ROOT / f"eval/v2/fresh/{t}/labels/{i}.json").read_text())))
score.SPLIT_FILE = ROOT / "eval/split.json"; score.DATA = ROOT / "runs"
sets.append(("v1 test split", ROOT / "runs", score.load_split("test"), lambda i: json.loads((ROOT / f"runs/labels/{i}.json").read_text())))
subprocess.run([str(ROOT / "build/tb_sim2"), "generate", "--out", str(ROOT / "runs/topo2")], capture_output=True)
score.SPLIT_FILE = ROOT / "eval/topology2/manifest.json"
sets.append(("topology 2 test", ROOT / "runs/topo2", score.load_split("test"), lambda i: json.loads((ROOT / f"runs/topo2/labels/{i}.json").read_text())))
for name, data, ids, lf in sets:
    r5 = r6 = 0; diffs = []
    for i in ids:
        lab = lf(i); a, b = an("tb_analyze5", data / "incidents" / i), an("tb_analyze6", data / "incidents" / i)
        o5, o6 = score.judge(lab, a)[0], score.judge(lab, b)[0]; r5 += o5; r6 += o6
        if (a["hypotheses"][0]["category"], a["hypotheses"][0]["service"]) != (b["hypotheses"][0]["category"], b["hypotheses"][0]["service"]):
            diffs.append(f"{i}: v5 {'✓' if o5 else '✗'} -> v6 {'✓' if o6 else '✗'} ({b['hypotheses'][0]['category']}/{b['hypotheses'][0]['service']})")
    print(f"- {name} (n={len(ids)}): v5 {r5}, v6 {r6}" + (f"; changed answers: {'; '.join(diffs)}" if diffs else "; no answer changed"))
