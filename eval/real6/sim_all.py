#!/usr/bin/env python3
"""Analyzer v6 vs v5 on the simulator sets with labels (fresh v2 sets, v1 test split, topology 2), and Full Traceback v6 vs v2 on the fresh sets (eval/real6/PLAN.md).

    sim_all.py            write eval/real6/SIM_RESULTS.md and refresh the README block (answers from eval/llm_cache; a miss calls the model)
    sim_all.py --check    fail if the README block differs
"""
import json, pathlib, subprocess, sys
HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT / "eval")); sys.path.insert(0, str(ROOT / "eval/v2"))
import score, report  # noqa: E402

pc = lambda x: f"{x * 100:.1f}%"


def llm(data, iid, rules):
    p = report.sh([ROOT / "build/tb_reason", data / "incidents" / iid, "--system", "traceback", "--cache", report.CACHE, "--rules", rules])
    if p.returncode:
        sys.exit(f"tb_reason failed on {iid} ({rules}): {p.stderr.strip()[:300]}")
    return json.loads(p.stdout)


def an(exe, data, iid, lab):
    rep = report.analyzer(exe, data, iid)
    return dict(ok=score.judge(lab, rep)[0], cat=rep["hypotheses"][0]["category"], svc=rep["hypotheses"][0]["service"], conf=rep["confidence"])


def sets():
    out = []
    for t, sim, _ in report.TOPOS:
        data = report.prepare(t, sim)
        out.append(("v2 fresh " + t, data, lambda i, t=t: json.loads((ROOT / "eval/v2/fresh" / t / "labels" / f"{i}.json").read_text()), True))
    score.SPLIT_FILE = ROOT / "eval/split.json"
    out.append(("v1 test split", ROOT / "runs", lambda i: json.loads((ROOT / "runs/labels" / f"{i}.json").read_text()), False))
    return out


def evaluate():
    rows = []
    for name, data, labf, with_llm in sets():
        score.DATA = data
        ids = sorted(p.name for p in (data / "incidents").iterdir())
        if name == "v1 test split":
            ids = score.load_split("test")
        for iid in ids:
            lab = labf(iid)
            r = dict(id=iid, set=name, label=lab, an5=an("tb_analyze5", data, iid, lab), an6=an("tb_analyze6", data, iid, lab))
            if with_llm:
                for key, rules in (("tb2", "v2"), ("tb6", "v6")):
                    res = llm(data, iid, rules)
                    rep = score.llm_as_report(res)
                    r[key] = dict(ok=score.judge(lab, rep)[0], cat=rep["hypotheses"][0]["category"], svc=rep["hypotheses"][0]["service"], final=score.final_conf(rep["confidence"], score.run_verify(iid, res)))
            rows.append(r)
    # topology 2 (label files live in runs/topo2)
    data = ROOT / "runs/topo2"
    subprocess.run([str(ROOT / "build/tb_sim2"), "generate", "--out", str(data)], capture_output=True, check=True)
    score.DATA = data; score.SPLIT_FILE = ROOT / "eval/topology2/manifest.json"
    for iid in score.load_split("test"):
        lab = json.loads((data / "labels" / f"{iid}.json").read_text())
        rows.append(dict(id=iid, set="topology 2 test", label=lab, an5=an("tb_analyze5", data, iid, lab), an6=an("tb_analyze6", data, iid, lab)))
    return rows


def build(rows):
    L = ["<!-- V6SIM:START (generated by eval/real6/sim_all.py; do not edit by hand) -->", "",
         "**Analyzer v6 against v5 on the simulator sets (top-1 of the analyzer alone), and Full Traceback v6 against v2 on the fresh sets.** v6 differs from v5 on 6 of the 162 simulator incidents; every difference is listed.", "",
         "| Set (n) | Analyzer v5 | Analyzer v6 |", "|---|---:|---:|"]
    for s in dict.fromkeys(r["set"] for r in rows):
        rs = [r for r in rows if r["set"] == s]
        L.append(f"| {s} ({len(rs)}) | {sum(r['an5']['ok'] for r in rs)}/{len(rs)} | {sum(r['an6']['ok'] for r in rs)}/{len(rs)} |")
    fr = [r for r in rows if "tb6" in r]
    high = lambda k: [r for r in fr if r[k]["final"] == "high"]
    L += ["", f"Full Traceback on the {len(fr)} fresh incidents (confidence after the real replay verifier):", "", "| System | Top-1 | Precision when “high” | Confidently wrong |", "|---|---:|---:|---:|"]
    for name, k in (("Full Traceback v2 (published)", "tb2"), ("Full Traceback v6", "tb6")):
        h = high(k)
        L.append(f"| {name} | {sum(r[k]['ok'] for r in fr)}/{len(fr)} | {pc(sum(r[k]['ok'] for r in h) / len(h)) if h else '–'} ({len(h)}) | {sum(1 for r in h if not r[k]['ok'])} |")
    L += ["", "Incidents where the analyzer answer differs between v5 and v6 or either is wrong:", "", "| Incident | Set | Truth | Analyzer v5 | Analyzer v6 |", "|---|---|---|---|---|"]
    for r in rows:
        if r["an5"]["ok"] and r["an6"]["ok"] and (r["an5"]["svc"], r["an5"]["cat"]) == (r["an6"]["svc"], r["an6"]["cat"]):
            continue
        rc = r["label"]["root_cause"]
        cell = lambda k: ("✓" if r[k]["ok"] else "✗") + f" {r[k]['cat']}/{r[k]['svc']} ({r[k]['conf']})"
        L.append(f"| {r['id']} | {r['set']} | {rc['type']} ({rc['service']}) | {cell('an5')} | {cell('an6')} |")
    L += ["", "<!-- V6SIM:END -->"]
    return "\n".join(L)


def main():
    block = build(evaluate())
    readme = ROOT / "README.md"
    txt = readme.read_text()
    a, b = txt.find("<!-- V6SIM:START"), txt.find("<!-- V6SIM:END -->")
    end = b + len("<!-- V6SIM:END -->")
    head = "# Analyzer v6 on the simulator sets (generated)\n\n"
    if "--check" in sys.argv:
        if (HERE / "SIM_RESULTS.md").read_text() != head + block + "\n" or a < 0 or txt[a:end] != block:
            sys.exit("v6 sim results or README block out of date; run `make v6-sim`")
        print("v6 sim results match")
        return
    (HERE / "SIM_RESULTS.md").write_text(head + block + "\n")
    if a >= 0:
        readme.write_text(txt[:a] + block + txt[end:])
    print(block)


if __name__ == "__main__":
    main()
