#!/usr/bin/env python3
"""Hybrid on the simulator fresh sets next to the raw-logs baseline and Full Traceback v2 (eval/real3/PLAN.md). Offline: every model answer is in eval/llm_cache.

    report.py            write eval/hybrid/RESULTS.md and refresh the README block
    report.py --check    fail if the README block differs from the regenerated one
"""
import pathlib, sys
HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
import sim_eval  # noqa: E402

pc = lambda x: f"{x * 100:.1f}%"
SYSTEMS = [("Raw logs → LLM (baseline)", "bl"), ("Full Traceback v2", "tb2"), ("**Hybrid**", "hy")]


def table(rows):
    L = ["| System | Top-1 | Precision when “high” (after verifier) | Confidently wrong | Wrong at medium or high | Decoy cases top-1 |", "|---|---:|---:|---:|---:|---:|"]
    dec = [r for r in rows if r["group"] == "decoy"]
    for name, k in SYSTEMS:
        s = sim_eval.summ(rows, k, "final")
        d = sim_eval.summ(dec, k, "final")
        prec = "–" if not s["high"] else f"{pc(s['high_ok'] / s['high'])} ({s['high']})"
        L.append(f"| {name} | {pc(s['top1'] / s['n'])} ({s['top1']}/{s['n']}) | {prec} | {pc(s['fc'] / s['n'])} ({s['fc']}) | {s['wrong_mh']} | {pc(d['top1'] / d['n'])} ({d['top1']}/{d['n']}) |")
    return L


def build(rows):
    mark = lambda ok: "✓" if ok else "✗"
    L = ["<!-- HYBRIDSIM:START (generated by eval/hybrid/report.py; do not edit by hand) -->", "",
         f"**Hybrid on the simulator fresh sets: {len(rows)} incidents, the same sets and the same cached model answers as the v2 table above.** The verifier is the real replay verifier; confidence is after it.", ""]
    L += table(rows)
    for t, title in (("t1", "Topology 1"), ("t2", "Topology 2")):
        rs = [r for r in rows if r["t"] == t]
        L += ["", f"{title}, n={len(rs)}:", ""] + table(rs)
    L += ["", "Every incident the hybrid or Full Traceback v2 got wrong (the answer and the confidence after the verifier are shown):", "", "| Incident | Truth | Baseline | Full Traceback v2 | Hybrid |", "|---|---|---|---|---|"]
    for r in rows:
        if r["tb2"]["ok"] and r["hy"]["ok"]:
            continue
        rc = r["label"]["root_cause"]
        cell = lambda k: f"{mark(r[k]['ok'])} {r[k]['cat']}/{r[k]['svc']} ({r[k]['final']})"
        L.append(f"| {r['id']} ({r['group']}) | {rc['type']} ({rc['service']}) | {cell('bl')} | {cell('tb2')} | {cell('hy')} |")
    ch = [r["id"] for r in rows if r["hy"]["hy"].get("chosen", {}).get("challenged_analyzer")]
    L += ["", "Wrong answers per system (all of them): " + "; ".join(f"{n.replace('**', '')}: {', '.join(r['id'] for r in rows if not r[k]['ok']) or 'none'}" for n, k in SYSTEMS) + ".",
          f"Incidents where a model proposal replaced the analyzer's top candidate: {', '.join(ch) if ch else 'none'}.", "", "<!-- HYBRIDSIM:END -->"]
    return "\n".join(L)


def main():
    block = build(sim_eval.evaluate("fresh"))
    readme = ROOT / "README.md"
    txt = readme.read_text()
    a, b = txt.find("<!-- HYBRIDSIM:START"), txt.find("<!-- HYBRIDSIM:END -->")
    end = b + len("<!-- HYBRIDSIM:END -->")
    if "--check" in sys.argv:
        if (HERE / "RESULTS.md").read_text() != "# Hybrid on the simulator fresh sets (generated)\n\n" + block + "\n" or a < 0 or txt[a:end] != block:
            sys.exit("hybrid sim results or README block out of date; run `make hybrid-sim`")
        print("hybrid sim results match")
        return
    (HERE / "RESULTS.md").write_text("# Hybrid on the simulator fresh sets (generated)\n\n" + block + "\n")
    if a >= 0:
        readme.write_text(txt[:a] + block + txt[end:])
    print(block)


if __name__ == "__main__":
    main()
