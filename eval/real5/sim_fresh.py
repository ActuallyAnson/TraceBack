#!/usr/bin/env python3
"""Analyzer v5 and Full Traceback v5 on the simulator fresh sets, next to Full Traceback v2 (eval/real5/PLAN.md). Offline when every answer is cached.

    sim_fresh.py            write eval/real5/SIM_RESULTS.md and refresh the README block
    sim_fresh.py --check    fail if the README block differs from the regenerated one
"""
import json, pathlib, sys
HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT / "eval")); sys.path.insert(0, str(ROOT / "eval/v2"))
import score, report  # noqa: E402

pc = lambda x: f"{x * 100:.1f}%"


def llm(data, iid, rules):
    args = [ROOT / "build/tb_reason", data / "incidents" / iid, "--system", "traceback", "--cache", report.CACHE, "--rules", rules]
    p = report.sh(args)
    if p.returncode:
        sys.exit(f"tb_reason failed on {iid} ({rules}): {p.stderr.strip()[:300]}")
    return json.loads(p.stdout)


def evaluate():
    rows = []
    for t, sim, _ in report.TOPOS:
        data = report.prepare(t, sim)
        score.DATA = data
        for iid in sorted(p.name for p in (data / "incidents").iterdir()):
            lab = json.loads((ROOT / "eval/v2/fresh" / t / "labels" / f"{iid}.json").read_text())
            r = dict(id=iid, group=lab["group"], label=lab)
            for key, exe in (("an4", "tb_analyze4"), ("an5", "tb_analyze5")):
                rep = report.analyzer(exe, data, iid)
                top = rep["hypotheses"][0]
                r[key] = dict(ok=score.judge(lab, rep)[0], cat=top["category"], svc=top["service"], final=rep["confidence"])
            for key, rules in (("tb2", "v2"), ("tb5", "v5")):
                res = llm(data, iid, rules)
                rep = score.llm_as_report(res)
                top = rep["hypotheses"][0]
                replay = score.run_verify(iid, res)
                r[key] = dict(ok=score.judge(lab, rep)[0], cat=top["category"], svc=top["service"], final=score.final_conf(rep["confidence"], replay))
            rows.append(r)
    return rows


def build(rows):
    S = [("Analyzer v4", "an4"), ("Analyzer v5", "an5"), ("Full Traceback v2 (published)", "tb2"), ("**Full Traceback v5**", "tb5")]
    L = ["<!-- V5SIM:START (generated by eval/real5/sim_fresh.py; do not edit by hand) -->", "",
         f"**Analyzer v5 and Full Traceback v5 on the simulator fresh sets ({len(rows)} incidents), the same sets as the v2 table; confidence after the real replay verifier.**", "",
         "| System | Top-1 | Precision when “high” | Confidently wrong | Wrong at medium or high |", "|---|---:|---:|---:|---:|"]
    for name, k in S:
        high = [r for r in rows if r[k]["final"] == "high"]
        L.append(f"| {name} | {pc(sum(r[k]['ok'] for r in rows) / len(rows))} ({sum(r[k]['ok'] for r in rows)}/{len(rows)}) | {pc(sum(r[k]['ok'] for r in high) / len(high)) if high else '–'} ({len(high)}) | {sum(1 for r in high if not r[k]['ok'])} | {sum(1 for r in rows if not r[k]['ok'] and r[k]['final'] in ('medium', 'high'))} |")
    L += ["", "Every incident any of them got wrong (answer and confidence after the verifier):", "", "| Incident | Truth | Analyzer v4 | Analyzer v5 | Full Traceback v2 | Full Traceback v5 |", "|---|---|---|---|---|---|"]
    for r in rows:
        if all(r[k]["ok"] for _, k in S):
            continue
        rc = r["label"]["root_cause"]
        cell = lambda k: ("✓" if r[k]["ok"] else "✗") + f" {r[k]['cat']}/{r[k]['svc']} ({r[k]['final']})"
        L.append(f"| {r['id']} ({r['group']}) | {rc['type']} ({rc['service']}) | {cell('an4')} | {cell('an5')} | {cell('tb2')} | {cell('tb5')} |")
    L += ["", "Wrong answers per system (all of them): " + "; ".join(f"{n.replace('**', '')}: {', '.join(r['id'] for r in rows if not r[k]['ok']) or 'none'}" for n, k in S) + ".", "", "<!-- V5SIM:END -->"]
    return "\n".join(L)


def main():
    block = build(evaluate())
    readme = ROOT / "README.md"
    txt = readme.read_text()
    a, b = txt.find("<!-- V5SIM:START"), txt.find("<!-- V5SIM:END -->")
    end = b + len("<!-- V5SIM:END -->")
    head = "# Analyzer v5 on the simulator fresh sets (generated)\n\n"
    if "--check" in sys.argv:
        if (HERE / "SIM_RESULTS.md").read_text() != head + block + "\n" or a < 0 or txt[a:end] != block:
            sys.exit("v5 sim results or README block out of date; run `make v5-sim`")
        print("v5 sim results match")
        return
    (HERE / "SIM_RESULTS.md").write_text(head + block + "\n")
    if a >= 0:
        readme.write_text(txt[:a] + block + txt[end:])
    print(block)


if __name__ == "__main__":
    main()
