#!/usr/bin/env python3
"""Render the three-system results table from docs/data/index.json (produced by eval/build_site.py).

    python3 eval/make_results.py            write eval/RESULTS.md and refresh the block in README.md
    python3 eval/make_results.py --check    fail if README.md's block differs from the generated one
Every number comes from saved runs via build_site.py; nothing is typed in by hand.
"""
import json, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent
idx = json.loads((ROOT / "docs/data/index.json").read_text())
S = idx["summary"]
SYS = [("baseline", "Raw logs → LLM (baseline)"), ("analyzer", "Analyzer only (no LLM)"), ("traceback_unverified", "Analyzer + LLM (no verifier)"), ("traceback", "**Full Traceback** (analyzer + LLM + verifier)")]
pc = lambda x: f"{x*100:.1f}%"
usd = lambda x: "$0" if not x else (f"${x:.4f}" if x < 0.01 else f"${x:.3f}")


def table(split, title):
    s = S[split]
    out = [f"**{title}** (n={s['traceback']['n']})", "", "| System | Top-1 | Precision when “high” | Confidently wrong | Cost / incident | Latency |", "|---|---:|---:|---:|---:|---:|"]
    for k, label in SYS:
        v = s[k]
        prec = "–" if v["prec_high"] is None else f"{pc(v['prec_high'])} ({v['high']})"
        lat = "<0.1 s" if v["latency"] < 1 else f"{v['latency']:.1f} s"
        out.append(f"| {label} | {pc(v['top1'])} | {prec} | {pc(v['fc'])} | {usd(v['cost'])} | {lat} |")
    return out


def block():
    a = idx["ablations"]
    L = ["<!-- RESULTS:START (generated by eval/make_results.py; do not edit by hand) -->", ""]
    L += table("test", "Held-out test split (headline)") + [""]
    L += ["Top-1 by kind of test incident:", "", "| System | Catalog fault types (n=%d) | Unseen fault types (n=%d, service localization only) |" % (S["test_catalog"]["traceback"]["n"], S["test_unseen"]["traceback"]["n"]), "|---|---:|---:|"]
    for k, label in SYS:
        L.append(f"| {label} | {pc(S['test_catalog'][k]['top1'])} | {pc(S['test_unseen'][k]['top1'])} |")
    L += [""] + table("dev", "Dev split (used for tuning; optimistic)") + [""]
    notes = []
    if idx.get("baseline_asrun_test_top1") is not None:
        notes.append(f"Baseline as first run on test: {pc(idx['baseline_asrun_test_top1'])}; one incident crashed the reply parser (a tool bug). After the fix and a re-run of that incident: {pc(S['test']['baseline']['top1'])} (shown above). See `eval/test_results/NOTES.md`.")
    if "baseline_plus_principles" in a:
        notes.append(f"Baseline given the same prompt principles as Traceback: {pc(a['baseline_plus_principles']['top1'])} top-1, {pc(a['baseline_plus_principles']['fc'])} confidently wrong (test, n={a['baseline_plus_principles']['n']}).")
    if "baseline_ultra_truncated_only" in a:
        notes.append(f"Baseline on a 1M-context model for the {a['baseline_ultra_truncated_only']['n']} incidents whose input was truncated: {pc(a['baseline_ultra_truncated_only']['top1'])} correct (thin evidence).")
    u = idx["usage"]
    notes.append(f"Model usage behind every number in the main comparison (all {u['calls']} recorded calls, both LLM systems, all {S['test']['traceback']['n'] + S['dev']['traceback']['n']} incidents, retries included): {u['prompt']/1e6:.1f}M prompt + {u['completion']/1e6:.2f}M completion tokens, about ${u['prompt']*0.0000003 + u['completion']*0.0000009:.2f} at the listed Nemotron 3 Super price.")
    notes.append(f"Baseline input exceeded the model's context window and was sampled by trace for {idx['truncated_baseline']['test']} of {S['test']['baseline']['n']} test incidents and {idx['truncated_baseline']['dev']} of {S['dev']['baseline']['n']} dev incidents.")
    L += ["Notes:", ""] + [f"- {n}" for n in notes] + ["", "<!-- RESULTS:END -->"]
    return "\n".join(L)


b = block()
readme = ROOT / "README.md"
txt = readme.read_text()
start, end = txt.find("<!-- RESULTS:START"), txt.find("<!-- RESULTS:END -->")
if "--check" in sys.argv:
    if start < 0 or end < 0:
        sys.exit("README.md has no results block")
    cur = txt[start:end + len("<!-- RESULTS:END -->")]
    if cur != b:
        sys.exit("README.md results block is out of date; run `make results`")
    print("README results block matches the generated table")
    sys.exit(0)
(ROOT / "eval/RESULTS.md").write_text("# Results (generated)\n\n" + b + "\n")
if start >= 0 and end >= 0:
    readme.write_text(txt[:start] + b + txt[end + len("<!-- RESULTS:END -->"):])
print(b)
