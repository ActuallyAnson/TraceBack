#!/usr/bin/env python3
"""Run the baseline, analyzer v1, analyzer v2 and Full Traceback v2 on the converted real-telemetry incidents (eval/real/PLAN.md); no tuning.

    evaluate.py            run (model answers come from eval/llm_cache; a miss calls the model and needs NEBIUS_API_KEY), write eval/real/RESULTS.md, refresh the README block
    evaluate.py --check    fail if RESULTS.md or the README block differ from the regenerated ones (offline)
"""
import json, pathlib, sys
HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT / "eval")); sys.path.insert(0, str(ROOT / "eval/v2"))
import score, report  # noqa: E402

CONVS = [("v1", "Converter v1: one trace per entry request (run second, after fixing a converter bug; see CONVERTER_NOTES.md)"), ("v0", "Converter v0: traces as exported (the first, pre-registered run)")]
SYS = [("bl", "Raw logs → LLM (baseline)"), ("an1", "Analyzer v1"), ("an2", "Analyzer v2"), ("tb2", "Full Traceback v2 (no replay verifier)")]


def view(rep):
    h = rep["hypotheses"][0]
    return dict(cat=h["category"], svc=h["service"], edge=h.get("edge"), conf=rep["confidence"])


def correct(lab, v):
    rc = lab["root_cause"]
    names = {rc["service"]} | ({rc["edge"]["from"], rc["edge"]["to"]} if rc.get("edge") else set())
    return v["svc"] in names or bool(v["edge"] and {v["edge"]["from"], v["edge"]["to"]} & names)


def run(conv):
    DATA = HERE / conv
    rows = []
    for lp in sorted((HERE / "labels").glob("*.json")):
        lab = json.loads(lp.read_text())
        iid = lab["id"]
        r = dict(id=iid, lab=lab)
        an1, an2 = report.analyzer("tb_analyze", DATA, iid), report.analyzer("tb_analyze2", DATA, iid)
        r["sym"] = an2["symptom"]
        r["an1"], r["an2"] = view(an1), view(an2)
        blres = report.llm(DATA, iid, "baseline", "v1")
        r["bl"] = view(score.llm_as_report(blres))
        r["bl_cost"] = blres["meta"]["cost_usd"]
        res = report.llm(DATA, iid, "traceback", "v2")
        r["tb2"] = view(score.llm_as_report(res))
        r["cost"] = res["meta"]["cost_usd"]
        for k, _ in SYS:
            r[k]["ok"] = correct(lab, r[k]) if lab["kind"] == "fault" else None
            r[k]["alarm"] = r[k]["conf"] in ("high", "medium") if lab["kind"] == "clean" else None
        rows.append(r)
    return rows


def tables(rows, title):
    faults, clean = [r for r in rows if r["lab"]["kind"] == "fault"], [r for r in rows if r["lab"]["kind"] == "clean"]
    L = [f"**{title}**", "", "| System | Fault runs localized | Clean runs with a “high” or “medium” alarm |", "|---|---:|---:|"]
    for k, name in SYS:
        L.append(f"| {name} | {sum(r[k]['ok'] for r in faults)}/{len(faults)} | {sum(r[k]['alarm'] for r in clean)}/{len(clean)} |")
    L += ["", "| Run | Truth | Entry failures | Baseline | Analyzer v1 | Analyzer v2 | Full Traceback v2 |", "|---|---|---:|---|---|---|---|"]
    for r in rows:
        lab = r["lab"]
        truth = "none (clean)" if lab["kind"] == "clean" else f"`{lab['flag']}={lab['variant']}` → {lab['root_cause']['service']}" + (f" ({lab['root_cause']['edge']['from']}→{lab['root_cause']['edge']['to']})" if lab["root_cause"]["edge"] else "")
        cell = lambda k: (f"{'✓' if r[k]['ok'] else '✗'} {r[k]['cat']}/{r[k]['svc']} ({r[k]['conf']})" if lab["kind"] == "fault" else f"{r[k]['cat']}/{r[k]['svc']} ({r[k]['conf']})")
        L.append(f"| {r['id']} | {truth} | {r['sym']['failed_traces']}/{r['sym']['traces']} | {cell('bl')} | {cell('an1')} | {cell('an2')} | {cell('tb2')} |")
    L += ["", f"Model cost for the {len(rows)} incidents, both LLM systems: ${sum(r['cost'] + r['bl_cost'] for r in rows):.3f}.", ""]
    return L


def main():
    nf, nc = 7, 3
    L = ["<!-- REAL:START (generated by eval/real/evaluate.py; do not edit by hand) -->", "",
         f"**Real telemetry (OpenTelemetry Demo, {nf} fault runs + {nc} clean runs, run twice with two converter versions; no significance claims).** Localization only: an answer counts if its service is the flagged service (or an endpoint of the faulty edge). "
         "On clean runs there is nothing to find, so the table shows the top answer and its confidence. “Entry failures” = failed entry requests / entry requests seen by the analyzer (a failure is an entry status of 500 or above).", ""]
    for conv, title in CONVS:
        L += tables(run(conv), title)
    L += ["<!-- REAL:END -->"]
    block = "\n".join(L)
    readme = ROOT / "README.md"
    txt = readme.read_text()
    a, b = txt.find("<!-- REAL:START"), txt.find("<!-- REAL:END -->")
    end = b + len("<!-- REAL:END -->")
    head = "# Real-telemetry results (generated)\n\n"
    if "--check" in sys.argv:
        if (HERE / "RESULTS.md").read_text() != head + block + "\n" or a < 0 or txt[a:end] != block:
            sys.exit("real-telemetry results or README block out of date; run `make real`")
        print("real-telemetry results match")
        return
    (HERE / "RESULTS.md").write_text(head + block + "\n")
    if a >= 0:
        readme.write_text(txt[:a] + block + txt[end:])
    print(block)


if __name__ == "__main__":
    main()
