#!/usr/bin/env python3
"""Post hoc, free, offline: does rule M's *dominance* (top score >= 10 and >= 1.5x the runner-up) mark its trustworthy answers? Writes eval/combo/DOMINANCE.md; `--check` regenerates and compares.
The ratio 1.5 was picked on development data only (RE2-SS, RE3-OB); RE2-OB, RE2-TT, RE3-SS and RE3-TT were not used to pick it. Descriptive, no significance claims."""
import glob, json, pathlib, sys
HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
J = lambda p: json.loads(pathlib.Path(p).read_text())
dom = lambda top, sec: top >= 10 and (sec is None or top / max(sec, 1e-9) >= 1.5)
L = ["# Rule M dominance (generated by eval/combo/dominance.py; post hoc, $0)", "",
     "A rule-M answer is **dominant** when its top service scores at least 10 and at least 1.5 times the runner-up. The ratio was picked on development data only (RE2-SS and RE3-OB).", "",
     "## Resource and network faults (RE2): how often a dominant answer is right", "", "| Archive | Faults with a dominant answer | Of those, correct | Clean windows with a dominant answer |", "|---|---:|---:|---:|"]
for t, name in (("ss", "RE2-SS Sock Shop (development)"), ("ob", "RE2-OB Online Boutique (unseen)"), ("tt", "RE2-TT Train Ticket (unseen)")):
    s = J(HERE.parent / f"metrics/scores_{t}.json")
    f = [x for x in s if x["kind"] == "fault"]; c = [x for x in s if x["kind"] == "clean"]
    d = lambda x: dom(x["top_score"], x["second"][1] if x["second"] else None)
    sel = [x for x in f if d(x)]
    L.append(f"| {name} | {len(sel)} of {len(f)} | {sum(x['top_service'] == x['truth'] for x in sel)} | {sum(d(x) for x in c)} of {len(c)} |")
labs = {}
for f in glob.glob(str(ROOT / "eval/transfer*/*/labels/*.json")):
    l = J(f); labs[l["id"]] = l
L += ["", "## Code-level faults (RE3): the same rule as a router in front of hybrid 2 (dominant → rule M at high confidence, else hybrid 2 unchanged)", "",
      "| Data | Model | Faults localized | Hybrid 2 alone | Wrong at high (router) | Wrong at high (hybrid 2 alone) |", "|---|---|---:|---:|---:|---:|"]
for name, h, m in (("RE3-OB (development)", "h2_re3ob.json", "mscores_re3ob.json"), ("RE3-SS", "h2_re3ss.json", "mscores_re3ss.json"), ("RE3-TT", "h2_re3tt.json", "mscores_re3tt.json"), ("RE3-SS", "h2u_re3ss.json", "mscores_re3ss.json"), ("RE3-TT", "h2u_re3tt.json", "mscores_re3tt.json")):
    H, M = J(HERE / h), J(HERE / m); hit = hh = wr = wh = n = 0
    for i, hv in H.items():
        l = labs[i]
        if l["kind"] != "fault": continue
        n += 1; v = sorted(M[i].items(), key=lambda kv: -kv[1])
        if v and dom(v[0][1], v[1][1] if len(v) > 1 else None): a, conf = v[0][0], "high"
        else: a, conf = hv["svc"], hv["conf"]
        t = l["root_cause"]["service"]
        hit += a == t; hh += hv["svc"] == t
        if a != t: wr += conf == "high"
        if hv["svc"] != t: wh += hv["conf"] == "high"
    L.append(f"| {name} | {'Ultra' if h.startswith('h2u') else 'Super'} | {hit}/{n} | {hh}/{n} | {wr} | {wh} |")
L += ["", "## Reading",
      "- On resource and network faults, dominance is a usable confidence signal for rule M: 65 of 68 dominant answers were correct across three systems (two of them unseen when the ratio was chosen), and only 5 of 90 clean windows had one.",
      "- On code-level faults the picture is mixed: the router localizes more on RE3-OB (development) and RE3-SS (26 of 30 against 18; 19 against 15 with Super), but fewer on Train Ticket (6 against 7 with Super, 13 against 18 with Ultra), where it is wrong at high confidence 6 times (hybrid 2 alone: 0). I did not investigate why.",
      "- So dominance can grade rule M's answers inside the resource-fault class, but nothing here tells the two fault classes apart in advance. It is a hint from post hoc analysis, not a validated result; RE3-SS and RE3-TT were already opened by earlier tests."]
out = "\n".join(L) + "\n"
p = HERE / "DOMINANCE.md"
if "--check" in sys.argv:
    sys.exit(0 if p.read_text() == out else "DOMINANCE.md out of date; run eval/combo/dominance.py")
p.write_text(out); print(out)
